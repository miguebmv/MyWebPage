const textNodeOriginals = new WeakMap();
const attributeOriginals = new WeakMap();
const translatableAttributes = ["aria-label", "alt", "title", "content"];
window.__i18nMissing = new Set();

function translateValue(value, language) {
  if (language !== "es") return value;
  const normalized = value.trim().replace(/\s+/g, " ");
  if (!(normalized in spanishTranslations) && normalized.split(/\s+/).length >= 3) {
    window.__i18nMissing.add(normalized);
  }
  return spanishTranslations[normalized] ?? value;
}

function translateTextNodes(language) {
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parent = node.parentElement;
        if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    },
  );

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  nodes.forEach((node) => {
    if (!textNodeOriginals.has(node)) textNodeOriginals.set(node, node.nodeValue);
    const original = textNodeOriginals.get(node);
    const trimmed = original.trim();
    const replacement = translateValue(trimmed, language);
    node.nodeValue = original.replace(trimmed, replacement);
  });
}

function translateAttributes(language) {
  document.querySelectorAll("*").forEach((element) => {
    let originals = attributeOriginals.get(element);
    if (!originals) {
      originals = {};
      translatableAttributes.forEach((attribute) => {
        if (element.hasAttribute(attribute)) {
          originals[attribute] = element.getAttribute(attribute);
        }
      });
      attributeOriginals.set(element, originals);
    }

    Object.entries(originals).forEach(([attribute, original]) => {
      element.setAttribute(attribute, translateValue(original, language));
    });
  });
}

function updateLanguageControls(language) {
  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });
}

function updateLanguageInUrl(language) {
  const url = new URL(window.location.href);
  url.searchParams.set("lang", language);
  window.history.replaceState({}, "", url);
}

function applyLanguage(language, { persist = false, updateUrl = false } = {}) {
  const selected = language === "es" ? "es" : "en";
  document.documentElement.lang = selected;
  document.documentElement.dataset.language = selected;

  translateTextNodes(selected);
  translateAttributes(selected);

  if (!document.documentElement.dataset.originalTitle) {
    document.documentElement.dataset.originalTitle = document.title;
  }
  document.title = translateValue(document.documentElement.dataset.originalTitle, selected);

  updateLanguageControls(selected);
  document.documentElement.classList.add("i18n-ready");

  if (persist) localStorage.setItem("mabravo-language", selected);
  if (updateUrl) updateLanguageInUrl(selected);

  window.dispatchEvent(new CustomEvent("site-language-change", { detail: { language: selected } }));
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLanguage = document.documentElement.dataset.language || "en";
  applyLanguage(initialLanguage);

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.language, { persist: true, updateUrl: true });
    });
  });
});
